#!/usr/bin/env python3
"""Resolve and write an explicit conda lock for macOS ARM64.

The output contains exact package URLs and MD5 hashes.  Resolution requires
network access to conda-forge but does not create or modify an environment.
"""

from __future__ import annotations

import json
import os
import platform
import subprocess
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "environment-osx-arm64.lock"
DIRECT_REQUIREMENTS = (
    "python=3.14.6",
    "numpy=2.3.4",
    "scipy=1.18.0",
    "pandas=2.3.3",
    "matplotlib=3.10.7",
    "sympy=1.14.0",
    "numba=0.63.1",
    "pytest=9.0.2",
)


def main() -> None:
    if platform.system() != "Darwin" or platform.machine().lower() not in {
        "arm64",
        "aarch64",
    }:
        raise RuntimeError("this release lock must be resolved on macOS ARM64")

    with tempfile.TemporaryDirectory(prefix="cavity-conda-lock-") as package_dir:
        env = os.environ.copy()
        env["CONDA_PKGS_DIRS"] = package_dir
        command = [
            "conda",
            "create",
            "--dry-run",
            "--json",
            "--override-channels",
            "-c",
            "conda-forge",
            "-p",
            str(Path(package_dir) / "unused-prefix"),
            *DIRECT_REQUIREMENTS,
        ]
        completed = subprocess.run(
            command,
            check=True,
            capture_output=True,
            text=True,
            env=env,
        )
        plan = json.loads(completed.stdout)

    records = plan.get("actions", {}).get("FETCH", [])
    if not records:
        raise RuntimeError("conda returned no package records")
    records = sorted(records, key=lambda record: record["url"])
    lines = [
        "# Explicit conda package lock",
        "# platform: osx-arm64",
        "# resolver: conda-forge",
        "# generated by: scripts/generate_conda_lock.py",
        "@EXPLICIT",
    ]
    lines.extend(f"{record['url']}#{record['md5']}" for record in records)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(records)} package records to {OUTPUT.name}")


if __name__ == "__main__":
    main()
