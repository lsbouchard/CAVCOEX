def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def make_taylor_spec(name: str, half_window: float, degree: int) -> TaylorSpec:
    if half_window <= 0.0 or degree < 1:
        raise ValueError("invalid Taylor specification")
    indices = np.flatnonzero(np.abs(H_GRID) <= half_window + 1.0e-12)
    if len(indices) <= degree:
        raise ValueError("Taylor window has too few points")
    field = H_GRID[indices]
    design = np.column_stack([field**power for power in range(degree + 1)])
    projection = np.linalg.pinv(design)
    return TaylorSpec(name, half_window, degree, indices, projection)


