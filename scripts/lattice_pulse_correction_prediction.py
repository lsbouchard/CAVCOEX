def write_outputs(
    coefficient_frame: pd.DataFrame,
    slope_frame: pd.DataFrame,
    metadata: dict[str, Any],
    output_root: Path,
) -> None:
    data_directory = output_root / "data_processed"
    generated_directory = output_root / "generated"
    data_directory.mkdir(parents=True, exist_ok=True)
    generated_directory.mkdir(parents=True, exist_ok=True)
    coefficient_path = data_directory / "lattice_pulse_correction_coefficients.csv"
    slope_path = data_directory / "lattice_pulse_correction_slope_predictions.csv"
    coefficient_frame.to_csv(coefficient_path, index=False)
    slope_frame.to_csv(slope_path, index=False)
    metadata["output_sha256"] = {
        str(coefficient_path.relative_to(output_root)): sha256(coefficient_path),
        str(slope_path.relative_to(output_root)): sha256(slope_path),
    }
    metadata_path = generated_directory / "lattice_pulse_correction_prediction_metadata.json"
    metadata_path.write_text(json.dumps(metadata, indent=2, sort_keys=True) + "\n")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, nargs="+", default=list(DEFAULT_RAW))
    parser.add_argument("--blocks-per-replica", type=int, default=DEFAULT_BLOCKS)
    parser.add_argument(
        "--bootstrap-draws", type=int, default=DEFAULT_BOOTSTRAP_DRAWS
    )
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument(
        "--output-root",
        type=Path,
        default=ROOT,
        help="root containing data_processed/ and generated/ output directories",
    )
    return parser.parse_args()


def main() -> None:
    arguments = parse_args()
    coefficients, slopes, metadata = analyze(
        tuple(path.resolve() for path in arguments.raw),
        arguments.blocks_per_replica,
        arguments.bootstrap_draws,
        arguments.seed,
    )
    write_outputs(coefficients, slopes, metadata, arguments.output_root.resolve())


if __name__ == "__main__":
    main()
