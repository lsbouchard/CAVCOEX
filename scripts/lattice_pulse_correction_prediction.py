"""Coefficient-level test of the first finite-volume pulse correction.

The four coefficients ``d0``, ``dchi``, ``a1``, and ``dn`` are estimated only
from phase-restricted finite-volume primitives and their local field
derivatives.  They are then inserted into the analytic formulas generated by
``derive_pulse_finite_size_corrections.py`` to predict the 1/V slopes of the
pulse center, magnitude, and FWHM.  Direct pulse slopes are fitted separately.

Replica/block bootstrap draws are shared between primitive and pulse analyses
at each lattice size, while different sizes are resampled independently.  The
resulting prediction--measurement comparison therefore retains their sampling
covariance without using a fitted pulse slope to estimate any coefficient.
"""

